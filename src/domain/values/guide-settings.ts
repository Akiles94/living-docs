/** Repository-level choices the core needs: title, folders, and how flows group by theme. */
export interface GuideSettings {
  readonly title: string;
  /** Repo-relative posix path of the hand-written flow sources. */
  readonly flowsDir: string;
  /** Repo-relative posix path of the generated guide. */
  readonly guideDir: string;
  /** Theme display order on the index; unknown themes sort after these, alphabetically. */
  readonly themeOrder: readonly string[];
  /** Reference kinds flows may cite as `{{kind:name}}`. */
  readonly referenceKinds: readonly string[];
  /**
   * Surfaces every flow's `## Entry points` must speak for, one `Label:` line each (a reference,
   * or why there is none) — e.g. `["CLI", "Desktop"]` to keep two front-ends in parity.
   */
  readonly entryPointSurfaces?: readonly string[];
  /**
   * Command a reader runs to regenerate the guide, shown in page banners and stale-page findings.
   * Defaults to `npx living-docs write`.
   */
  readonly regenerateCommand?: string;
}

/** The command to regenerate the guide: the repository's own, else the CLI's. */
export function regenerateCommandOf(settings: Pick<GuideSettings, "regenerateCommand">): string {
  return settings.regenerateCommand ?? "npx living-docs write";
}

/** First line of every generated page; only files carrying it are ever deleted. */
export function generatedBanner(settings: Pick<GuideSettings, "regenerateCommand">): string {
  return `<!-- Generated by living-docs — do not edit. Run \`${regenerateCommandOf(settings)}\`. -->`;
}
