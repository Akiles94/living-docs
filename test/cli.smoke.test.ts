import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

const packageRoot = join(import.meta.dirname, "..");
const cli = join(packageRoot, "dist/cli.js");
let repo: string;

const run = (...args: string[]) =>
  spawnSync(process.execPath, [cli, ...args], { cwd: repo, encoding: "utf8" });

beforeAll(() => {
  const tsup = join(packageRoot, "node_modules/tsup/dist/cli-default.js");
  execFileSync(process.execPath, [tsup, "--silent"], { cwd: packageRoot, stdio: "inherit" });
  repo = mkdtempSync(join(tmpdir(), "living-docs-smoke-"));
  cpSync(join(import.meta.dirname, "fixtures/sample-repo"), repo, { recursive: true });
}, 120_000);
afterAll(() => rmSync(repo, { recursive: true, force: true }));

describe("living-docs CLI on a sample repository", () => {
  it("check fails before the guide exists, write creates it, then check passes", () => {
    expect(run("check").status).toBe(1);

    const write = run("write");
    expect(write.stdout).toContain(
      "✓ Guide written: 1 flows, 3 citations, 2/2 exports documented.",
    );
    expect(readFileSync(join(repo, "docs/guide/flows/greet-visitor.md"), "utf8")).toMatch(
      /^<!-- Generated by living-docs — do not edit\. Run `npx living-docs write`\. -->/,
    );

    const check = run("check");
    expect(check.status).toBe(0);
    expect(check.stdout).toContain("✓ Guide up to date");
  });

  it("fails the check when the code drifts from the flows", () => {
    writeFileSync(
      join(repo, "src/greeter.ts"),
      "/** Renamed. Says hi to a visitor. */\nexport const hi = 1;\n",
    );
    const check = run("check");
    expect(check.status).toBe(1);
    expect(check.stdout).toContain("[broken-reference]");
  });

  it("prints the agent prompt and rejects unknown commands", () => {
    expect(run("prompt", "init").stdout).toContain("# Adopt living-docs in this repository");
    expect(run("publish").status).toBe(2);
  });
});
